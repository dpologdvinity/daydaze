// The food places of Daydaze: about 100 restaurants, cafes and street stalls,
// as pure data. Every name is original, and each menu has real dishes with
// placeholder coin prices (food is free until the wallet lands). Three venues
// have an interior room; the rest stand in the city as storefronts.
import { byTier } from "../age.ts";
import type { RoomId } from "../rooms.ts";
import type { NeighborhoodId } from "../dialogue/types.ts";

export type MenuItem = {
  id: string;
  name: string;
  /** Placeholder coins; food is free until the wallet lands. */
  price: number;
  kind: "food" | "drink";
};

export type FoodGroup = "food-street" | "cafe" | "restaurant";

export type FoodVenue = {
  id: string;
  name: string;
  /** A short cuisine label shown under the name. */
  cuisine: string;
  group: FoodGroup;
  neighborhood: NeighborhoodId;
  menu: readonly MenuItem[];
  /** The interior room behind a city door, when the venue has one. */
  room?: RoomId;
};

type Entry = readonly [name: string, price: number, kind?: "food" | "drink"];

function venue(
  id: string,
  name: string,
  cuisine: string,
  group: FoodGroup,
  neighborhood: NeighborhoodId,
  menu: readonly Entry[],
  room?: RoomId,
): FoodVenue {
  return {
    id,
    name,
    cuisine,
    group,
    neighborhood,
    menu: menu.map(([itemName, price, kind = "food"]) => ({
      id: `${id}/${itemName.toLowerCase().replace(/[^a-z0-9]+/g, "-")}`,
      name: itemName,
      price,
      kind,
    })),
    ...(room ? { room } : {}),
  };
}

