export const FOOD_VENUES: readonly FoodVenue[] = [
  ...FOOD_STREET,
  ...RESTAURANTS,
  ...CAFES,
];

const VENUE_INDEX = new Map(FOOD_VENUES.map((v) => [v.id, v] as const));

export function venueById(id: string): FoodVenue | undefined {
  return VENUE_INDEX.get(id);
}

/** Finds a menu item and the venue that serves it. */
export function menuItemById(
  id: string,
): { venue: FoodVenue; item: MenuItem } | undefined {
  for (const venue of FOOD_VENUES) {
    const item = venue.menu.find((m) => m.id === id);
    if (item) return { venue, item };
  }
  return undefined;
}
